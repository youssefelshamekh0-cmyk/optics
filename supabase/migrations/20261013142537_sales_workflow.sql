create table public.sales (
  id uuid primary key default gen_random_uuid(),
  invoice_number bigint generated by default as identity unique,
  branch_id uuid not null references public.branches(id) on delete restrict,
  customer_id uuid not null references public.customers(id) on delete restrict,
  created_by uuid references auth.users(id) on delete set null,
  total_amount numeric(12,2) not null check (total_amount > 0),
  discount_amount numeric(12,2) not null default 0 check (discount_amount >= 0 and discount_amount <= total_amount),
  grand_total numeric(12,2) generated always as (total_amount - discount_amount) stored,
  prescription jsonb not null default '{}'::jsonb,
  notes varchar(1000),
  delivery_status text not null default 'pending' check (delivery_status in ('pending','processing','ready','delivered','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.sale_items (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales(id) on delete cascade,
  item_name varchar(160) not null,
  quantity integer not null check (quantity between 1 and 100),
  unit_price numeric(12,2) not null check (unit_price > 0),
  line_total numeric(14,2) generated always as (quantity * unit_price) stored
);

create table public.sale_payments (
  id uuid primary key default gen_random_uuid(),
  sale_id uuid not null references public.sales(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null check (payment_method in ('cash','card','instapay','other')),
  notes varchar(500),
  received_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index sales_branch_created_idx on public.sales(branch_id, created_at desc);
create index sales_customer_idx on public.sales(customer_id, created_at desc);
create index sale_items_sale_idx on public.sale_items(sale_id);
create index sale_payments_sale_idx on public.sale_payments(sale_id, created_at);

alter table public.sales enable row level security;
alter table public.sale_items enable row level security;
alter table public.sale_payments enable row level security;
revoke all on table public.sales, public.sale_items, public.sale_payments from anon, authenticated;
grant all on table public.sales, public.sale_items, public.sale_payments to service_role;
grant usage, select on sequence public.sales_invoice_number_seq to service_role;

insert into public.permissions(key, description) values ('sales.read', 'عرض الفواتير') on conflict (key) do nothing;
insert into public.role_permissions(role_id, permission_id)
select r.id, p.id
