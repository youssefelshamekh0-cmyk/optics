where r.key in ('super_admin','salesperson') and p.key = 'sales.read'
on conflict do nothing;

create or replace function public.create_optics_sale(
  p_branch_id uuid,
  p_customer_id uuid,
  p_created_by uuid,
  p_discount numeric,
  p_items jsonb,
  p_prescription jsonb,
  p_initial_payment numeric,
  p_payment_method text,
  p_notes text
) returns table (sale_id uuid, invoice_number bigint)
language plpgsql security invoker set search_path = public
as $$
declare
  v_item jsonb;
  v_name text;
  v_quantity integer;
  v_unit_price numeric(12,2);
  v_total numeric(12,2) := 0;
  v_grand_total numeric(12,2);
  v_sale_id uuid;
  v_invoice_number bigint;
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 20 then
    raise exception 'sale requires between 1 and 20 items';
  end if;
  for v_item in select value from jsonb_array_elements(p_items) as item_rows(value) loop
    begin
      v_name := trim(v_item->>'name');
      v_quantity := (v_item->>'quantity')::integer;
      v_unit_price := round((v_item->>'unitPrice')::numeric, 2);
    exception when others then
      raise exception 'invalid sale item';
    end;
    if length(v_name) < 2 or length(v_name) > 160 or v_quantity not between 1 and 100 or v_unit_price <= 0 then
      raise exception 'invalid sale item';
    end if;
    v_total := v_total + (v_quantity * v_unit_price);
  end loop;
  if p_discount is null or p_discount < 0 or p_discount > v_total then raise exception 'invalid discount'; end if;
  v_grand_total := v_total - p_discount;
  if p_initial_payment is null or p_initial_payment < 0 or p_initial_payment > v_grand_total then raise exception 'invalid initial payment'; end if;
  if p_initial_payment > 0 and p_payment_method not in ('cash','card','instapay','other') then raise exception 'invalid payment method'; end if;

  insert into public.sales(branch_id,customer_id,created_by,total_amount,discount_amount,prescription,notes)
  values(p_branch_id,p_customer_id,p_created_by,v_total,p_discount,coalesce(p_prescription,'{}'::jsonb),nullif(trim(p_notes),''))
  returning id, sales.invoice_number into v_sale_id, v_invoice_number;

  for v_item in select value from jsonb_array_elements(p_items) as item_rows(value) loop
    insert into public.sale_items(sale_id,item_name,quantity,unit_price)
    values(v_sale_id,trim(v_item->>'name'),(v_item->>'quantity')::integer,round((v_item->>'unitPrice')::numeric,2));
  end loop;
  if p_initial_payment > 0 then
    insert into public.sale_payments(sale_id,amount,payment_method,received_by)
    values(v_sale_id,p_initial_payment,p_payment_method,p_created_by);
  end if;
  return query select v_sale_id, v_invoice_number;
end;
$$;

create or replace function public.record_sale_payment(
  p_sale_id uuid, p_amount numeric, p_payment_method text, p_received_by uuid, p_notes text
) returns uuid
language plpgsql security invoker set search_path = public
as $$
declare
  v_grand_total numeric(12,2);
  v_delivery_status text;
  v_paid numeric(12,2);
  v_payment_id uuid;
begin
  select s.grand_total, s.delivery_status into v_grand_total, v_delivery_status
  from public.sales s where s.id = p_sale_id for update;
  if not found then raise exception 'sale not found'; end if;
  if v_delivery_status = 'cancelled' then raise exception 'cancelled sale cannot receive payments'; end if;
  if p_amount is null or p_amount <= 0 then raise exception 'invalid payment amount'; end if;
  if p_payment_method not in ('cash','card','instapay','other') then raise exception 'invalid payment method'; end if;
  select coalesce(sum(sp.amount),0) into v_paid from public.sale_payments sp where sp.sale_id = p_sale_id;
  if p_amount > v_grand_total - v_paid then raise exception 'payment exceeds remaining balance'; end if;
  insert into public.sale_payments(sale_id,amount,payment_method,notes,received_by)
  values(p_sale_id,p_amount,p_payment_method,nullif(trim(p_notes),''),p_received_by)
  returning id into v_payment_id;
  return v_payment_id;
end;
$$;

